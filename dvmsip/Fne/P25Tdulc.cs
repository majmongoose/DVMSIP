        /// <summary>
        /// Encodes in place: the first 12 hexbits (72 bits) of <paramref name="data"/> are the message,
        /// and all 24 hexbits (18 bytes) are replaced with the codeword.
        /// </summary>
        public static void Encode(byte[] data)
        {
            var codeword = new byte[24];
            for (int i = 0; i < 24; i++)
            {
                for (int j = 0; j < 12; j++)
                    codeword[i] ^= Gf6Mult(Bin2Hex(data, j * 6), EncodeMatrix[j, i]);
            }

            for (int i = 0; i < 24; i++)
                Hex2Bin(codeword[i], data, i * 6);
        }

        private static byte Gf6Mult(byte a, byte b)
        {
            byte p = 0;
            for (int i = 0; i < 6; i++)
            {
                if ((b & 0x01) == 0x01)
                    p ^= a;

                a <<= 1;
                if ((a & 0x40) == 0x40)
                    a ^= 0x43;      // primitive polynomial : x ^ 6 + x + 1

                b >>= 1;
            }

            return p;
        }

        private static byte Bin2Hex(byte[] input, int offset)
        {
            byte output = 0;
            for (int i = 0; i < 6; i++)
            {
                int bit = offset + i;
                if ((input[bit >> 3] & (0x80 >> (bit & 7))) != 0)
                    output |= (byte)(0x20 >> i);
            }

            return output;
        }

        private static void Hex2Bin(byte input, byte[] output, int offset)
        {
            for (int i = 0; i < 6; i++)
            {
                int bit = offset + i;
                byte mask = (byte)(0x80 >> (bit & 7));
                if ((input & (0x20 >> i)) != 0)
                    output[bit >> 3] |= mask;
                else
                    output[bit >> 3] &= (byte)~mask;
            }
        }
    }
